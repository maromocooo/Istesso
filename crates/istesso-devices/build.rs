//! Makes the list of adapters from the directories under `adapters/`.
//!
//! Adding an adapter means adding a directory. Nothing in the core names an
//! adapter, so nothing in the core changes (ADR 0012).

use std::fmt::Write as _;
use std::path::PathBuf;
use std::{env, fs};

fn main() {
    let root =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("set by cargo")).join("adapters");
    println!("cargo:rerun-if-changed={}", root.display());

    let mut names: Vec<String> = Vec::new();
    if let Ok(entries) = fs::read_dir(&root) {
        for entry in entries.flatten() {
            let path = entry.path();
            if !path.join("adapter.rs").is_file() {
                continue;
            }
            let name = entry.file_name().to_string_lossy().into_owned();
            let valid = name.starts_with(|c: char| c.is_ascii_lowercase())
                && name
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
            assert!(
                valid,
                "adapter directory `{name}`: use lower-case letters, digits and `_`, starting with a letter"
            );
            println!(
                "cargo:rerun-if-changed={}",
                path.join("adapter.rs").display()
            );
            names.push(name);
        }
    }
    names.sort();

    let mut code = String::from("// Generated by build.rs from the directories under adapters/.\n");
    for name in &names {
        let file = root.join(name).join("adapter.rs");
        writeln!(
            code,
            "#[allow(clippy::module_inception)]\npub mod {name} {{\n    include!({:?});\n}}",
            file.display().to_string()
        )
        .expect("writing to a string");
    }
    code.push_str("\n/// Every adapter that was built in, with the name of its directory.\n");
    code.push_str(
        "pub fn entries() -> Vec<(&'static str, istesso_device_api::AdapterEntry)> {\n    vec![\n",
    );
    for name in &names {
        writeln!(code, "        ({name:?}, {name}::entry()),").expect("writing to a string");
    }
    code.push_str("    ]\n}\n");

    let out = PathBuf::from(env::var("OUT_DIR").expect("set by cargo")).join("adapters.rs");
    fs::write(out, code).expect("writing the generated list of adapters");
}
