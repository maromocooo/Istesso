/// The flag a modifier key holds while it is down; nil for other keys.
func modifierFlag(_ code: UInt32) -> CGEventFlags? {
    switch code {
    case 42, 54: return .maskShift
    case 29, 97: return .maskControl
    case 56, 100: return .maskAlternate
    case 125, 126: return .maskCommand
    default: return nil
    }
}

