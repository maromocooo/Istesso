// Copy and paste of text for the Mac host (trial only; docs/m4-clipboard-spec.md, ADR 0022).
//
// The trial agent says hello and hands the text of a paste over on clipboard.sock (beside the
// input socket); the marks of a copy or a paste come among the keys on the input socket, in their
// order. The answers go to the agent's clipboard-answer.sock, with the mark's nonce. Nothing of
// the text, its size or the nonces is ever written anywhere: counts only.

import AppKit
import Carbon

/// The pasteboard, behind a small face, so that --self-test uses one of its own (never the
/// Studio's real one).
protocol Board: AnyObject {
    var changeCount: Int { get }
    /// Every type of every item (to look for the secret markers before any text is read).
    func types() -> [String]
    func plainText() -> String?
    /// The bytes of the plain text, without making a string of it.
    func plainTextLength() -> Int?
    /// Puts text for this Mac only (not handed to other devices), marked as transient (clipboard
    /// tools do not keep it); says the change count after.
    func put(_ text: String) -> Int
    func clear()
}

final class SystemBoard: Board {
    let pasteboard: NSPasteboard
    init(_ pasteboard: NSPasteboard = .general) { self.pasteboard = pasteboard }
    var changeCount: Int { pasteboard.changeCount }
    func types() -> [String] { (pasteboard.pasteboardItems ?? []).flatMap { $0.types.map(\.rawValue) } }
    func plainText() -> String? { pasteboard.string(forType: NSPasteboard.PasteboardType("public.utf8-plain-text")) }
    func plainTextLength() -> Int? { pasteboard.data(forType: NSPasteboard.PasteboardType("public.utf8-plain-text"))?.count }
    func put(_ text: String) -> Int {
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(text, forType: NSPasteboard.PasteboardType("public.utf8-plain-text"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }
    func clear() { pasteboard.clearContents() }
}

/// The markers that say an item is not to be copied on: a password manager's concealed text, and
/// the transient and generated kinds.
let secretMarkers: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

/// What text may travel: at most 65536 bytes of UTF-8; not empty; no control characters but
/// tab, line feed and carriage return.
enum TextVerdict: String { case text, tooLarge = "too_large", notText = "not_text" }
func judgeText(_ text: String) -> TextVerdict {
    if text.utf8.count > 65536 { return .tooLarge }
    if text.isEmpty { return .notText }
    let bad = text.unicodeScalars.contains { scalar in
        let v = scalar.value
        return (v < 0x20 && v != 0x09 && v != 0x0a && v != 0x0d) || (0x7f...0x9f).contains(v)
    }
    return bad ? .notText : .text
}

/// The answer to the agent: `text` only with the result text, `why` only with refused.
func clipboardAnswer(nonce: String, result: String, text: String? = nil, why: String? = nil) -> [String: Any] {
    var answer: [String: Any] = ["kind": "answer", "nonce": nonce, "result": result]
    if result == "text", let text { answer["text"] = text }
    if result == "refused", let why { answer["why"] = why }
    return answer
}

final class ClipboardBridge {
    let board: Board
    private var socketFd: Int32 = -1
    private var answerFd: Int32 = -1
    private var answerPath = ""
    private var source: DispatchSourceRead?
    /// Texts of pastes, by nonce, kept for 2 s.
    private var texts: [String: (text: String, at: TimeInterval)] = [:]
    /// The change count after the host's own last paste (to withdraw it before a text-less one).
    private var ownChange: Int?
    private(set) var counts: [String: Int] = [:]
    /// Posts a chord to the application (Command and a key), as the input does; set by the host.
    var postChord: (_ code: UInt32) -> Void = { _ in }
    /// Whether keys may go to the application now (the input's own rule).
    var keysAllowed: () -> Bool = { false }
    /// The application whose focused element is looked at before a copy.
    var targetPid: () -> pid_t? = { nil }
    /// Runs Accessibility work away from the input, and its result on the main queue.
    var lookout: Lookout?

    init(board: Board) { self.board = board }

    /// Opens clipboard.sock beside the input socket (0600, room for 256 KiB) and the sending side
    /// for the agent's answers.
    func open(beside inputSocket: String) -> Bool {
        let folder = (inputSocket as NSString).deletingLastPathComponent
        let path = (folder as NSString).appendingPathComponent("clipboard.sock")
        answerPath = (folder as NSString).appendingPathComponent("clipboard-answer.sock")
        // Only a socket left by an earlier run is taken away.
        var info = stat()
        if lstat(path, &info) == 0, (info.st_mode & S_IFMT) == S_IFSOCK { unlink(path) }
        socketFd = socket(AF_UNIX, SOCK_DGRAM, 0)
        guard socketFd >= 0, bindUnix(socketFd, path) else { return false }
        chmod(path, 0o600)
        var room: Int32 = 256 * 1024
        setsockopt(socketFd, SOL_SOCKET, SO_RCVBUF, &room, socklen_t(MemoryLayout<Int32>.size))
        _ = fcntl(socketFd, F_SETFL, O_NONBLOCK)
        answerFd = socket(AF_UNIX, SOCK_DGRAM, 0)
        setsockopt(answerFd, SOL_SOCKET, SO_SNDBUF, &room, socklen_t(MemoryLayout<Int32>.size))
        let fd = socketFd
        let source = DispatchSource.makeReadSource(fileDescriptor: fd, queue: .main)
        source.setEventHandler { [weak self] in
            var buffer = [UInt8](repeating: 0, count: 192 * 1024)
            while true {
                let n = recv(fd, &buffer, buffer.count, 0)
                guard n > 0 else { break }
                self?.take(Data(buffer[0..<n]))
            }
        }
        source.resume()
        self.source = source
        return true
    }

    /// One datagram of clipboard.sock.
    func take(_ data: Data) {
        guard let object = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let kind = object["kind"] as? String, let nonce = object["nonce"] as? String, isNonce(nonce) else { return }
        switch kind {
        case "hello":
            // At once: the agent waits 0.3 s for it.
            send(["kind": "hello", "nonce": nonce])
            counts["hello", default: 0] += 1
        case "paste_text":
            guard let text = object["text"] as? String else { return }
            let now = ProcessInfo.processInfo.systemUptime
            texts = texts.filter { now - $0.value.at < 2 }
            texts[nonce] = (text, now)
        default:
            break
        }
    }

    private func isNonce(_ nonce: String) -> Bool {
        nonce.count == 32 && nonce.unicodeScalars.allSatisfy { CharacterSet(charactersIn: "0123456789abcdef").contains($0) }
    }

    private func send(_ value: [String: Any]) {
        guard answerFd >= 0, let data = try? JSONSerialization.data(withJSONObject: value) else { return }
        var address = sockaddr_un()
        address.sun_family = sa_family_t(AF_UNIX)
        let bytes = Array(answerPath.utf8)
        guard bytes.count < MemoryLayout.size(ofValue: address.sun_path) else { return }
        withUnsafeMutableBytes(of: &address.sun_path) { raw in raw.copyBytes(from: bytes); raw[bytes.count] = 0 }
        _ = data.withUnsafeBytes { buffer in
            withUnsafePointer(to: &address) {
                $0.withMemoryRebound(to: sockaddr.self, capacity: 1) {
                    sendto(answerFd, buffer.baseAddress, buffer.count, 0, $0, socklen_t(MemoryLayout<sockaddr_un>.size))
                }
            }
        }
    }

    func answer(_ nonce: String, _ result: String, text: String? = nil, why: String? = nil, what: String) {
        counts["\(what)_\(result)", default: 0] += 1
        send(clipboardAnswer(nonce: nonce, result: result, text: text, why: why))
        note("clipboard: \(what) answered \(result) (\(counts["\(what)_\(result)"] ?? 0) so far)")
    }

    /// The text of a paste, if it has come.
    func textFor(_ nonce: String) -> String? { texts[nonce]?.text }

    // ---- A copy ----

    func copy(nonce: String, cut: Bool) {
        guard keysAllowed(), !screenLocked() else { return answer(nonce, "none", what: "copy") }
        // Before any key: a secure input on this Mac, or a password field in front, refuses.
        if IsSecureEventInputEnabled() { return answer(nonce, "refused", why: "secure_input", what: "copy") }
        guard let pid = targetPid() else { return answer(nonce, "none", what: "copy") }
        let look = { [weak self] in
            let subrole = focusedSubrole(pid)
            DispatchQueue.main.async { self?.copyAfterLook(nonce: nonce, cut: cut, subrole: subrole) }
        }
        if let lookout { lookout.act(look) } else { look() }
    }

    private func copyAfterLook(nonce: String, cut: Bool, subrole: String?) {
        if subrole == "AXSecureTextField" { return answer(nonce, "refused", why: "password_field", what: "copy") }
        // Looked at again after the Accessibility look, which took time: still allowed, not locked.
        guard keysAllowed(), !screenLocked() else { return answer(nonce, "none", what: "copy") }
        if IsSecureEventInputEnabled() { return answer(nonce, "refused", why: "secure_input", what: "copy") }
        let before = board.changeCount
        postChord(cut ? 45 : 46)  // X or C
        let began = ProcessInfo.processInfo.systemUptime
        func look() {
            if board.changeCount != before { return finishCopy(nonce: nonce) }
            if ProcessInfo.processInfo.systemUptime - began >= 0.5 { return answer(nonce, "none", what: "copy") }
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.01) { look() }
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.01) { look() }
    }

    func finishCopy(nonce: String) {
        // The markers, the size and the text all from one and the same contents (change count).
        let seen = board.changeCount
        // The markers first; the text is not read when one is there.
        if board.types().contains(where: { secretMarkers.contains($0) }) {
            return answer(nonce, "refused", why: "secret_marker", what: "copy")
        }
        // Too large is told by the data's length, before any string is made of it.
        if let length = board.plainTextLength(), length > 65536 { return answer(nonce, "too_large", what: "copy") }
        guard let text = board.plainText(), board.changeCount == seen else { return answer(nonce, "none", what: "copy") }
        switch judgeText(text) {
        case .text: answer(nonce, "text", text: text, what: "copy")
        case .tooLarge: answer(nonce, "too_large", what: "copy")
        case .notText: answer(nonce, "not_text", what: "copy")
        }
    }

    // ---- A paste ----

    /// A paste whose text is here (or none is needed). Says whether it was done.
    func paste(nonce: String, withText: Bool) {
        if !withText {
            // A text the host put there earlier is taken back first; an application's own stays.
            if let own = ownChange, own == board.changeCount { board.clear() }
            guard keysAllowed(), !screenLocked() else { return answer(nonce, "none", what: "paste") }
            postChord(47)  // V
            return answer(nonce, "pasted", what: "paste")
        }
        guard let text = texts.removeValue(forKey: nonce)?.text else { return answer(nonce, "none", what: "paste") }
        switch judgeText(text) {
        case .tooLarge: return answer(nonce, "too_large", what: "paste")
        case .notText: return answer(nonce, "not_text", what: "paste")
        case .text: break
        }
        guard keysAllowed(), !screenLocked() else { return answer(nonce, "none", what: "paste") }
        ownChange = board.put(text)
        postChord(47)  // V; the pasteboard is not put back afterwards
        answer(nonce, "pasted", what: "paste")
    }
}

/// The subrole of an application's focused element (AXSecureTextField for a password field);
/// nil when it cannot be read.
func focusedSubrole(_ pid: pid_t) -> String? {
    let app = AXUIElementCreateApplication(pid)
    var element: CFTypeRef?
    guard AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &element) == .success, let element else { return nil }
    var subrole: CFTypeRef?
    guard AXUIElementCopyAttributeValue(element as! AXUIElement, kAXSubroleAttribute as CFString, &subrole) == .success else { return nil }
    return subrole as? String
}

/// Binds a datagram socket to a path.
func bindUnix(_ fd: Int32, _ path: String) -> Bool {
    var address = sockaddr_un()
    address.sun_family = sa_family_t(AF_UNIX)
    let bytes = Array(path.utf8)
    guard bytes.count < MemoryLayout.size(ofValue: address.sun_path) else { return false }
    withUnsafeMutableBytes(of: &address.sun_path) { raw in raw.copyBytes(from: bytes); raw[bytes.count] = 0 }
    return withUnsafePointer(to: &address) {
        $0.withMemoryRebound(to: sockaddr.self, capacity: 1) { Darwin.bind(fd, $0, socklen_t(MemoryLayout<sockaddr_un>.size)) == 0 }
    }
}

/// The marks of the input socket that belong to copy and paste, and what waits for a paste's text:
/// the events that come after a paste whose text is not here yet are held, in their order, for
/// at most 0.2 s.
final class PasteGate {
    private(set) var waitingFor: String?
    private var since: TimeInterval = 0
    private(set) var held: [Data] = []
    func begin(_ nonce: String, now: TimeInterval) { waitingFor = nonce; since = now; held = [] }
    func hold(_ data: Data) { held.append(data) }
    func expired(now: TimeInterval) -> Bool { waitingFor != nil && now - since > 0.2 }
    func end() -> [Data] { waitingFor = nil; let out = held; held = []; return out }
}
