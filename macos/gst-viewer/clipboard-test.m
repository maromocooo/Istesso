// Tests clipboard.h (the everyday trial's copy and paste, ADR 0022) without a window, a
// pasteboard or a socket. Built and run by build.sh.
#import "clipboard.h"

static int failures = 0;
#define CHECK(condition)                                                        \
    do {                                                                        \
        if (!(condition)) {                                                     \
            fprintf(stderr, "clipboard-test: failed: %s (line %d)\n", #condition, __LINE__); \
            failures++;                                                         \
        }                                                                       \
    } while (0)

int main(void) {
    @autoreleasepool {
        NSEventModifierFlags command = NSEventModifierFlagCommand;
        // Command alone, by the layout's letter; Caps Lock and Fn do not matter.
        CHECK(clipboard_key(8, @"c", command) == 'c');
        CHECK(clipboard_key(7, @"x", command | NSEventModifierFlagCapsLock) == 'x');
        CHECK(clipboard_key(9, @"v", command | NSEventModifierFlagFunction) == 'v');
        CHECK(clipboard_key(9, @"V", command) == 'v');
        // Another layout: the letter decides, not the place (Dvorak's C is not on the ANSI C).
        CHECK(clipboard_key(34, @"c", command) == 'c');
        CHECK(clipboard_key(8, @"j", command) == 0);
        // A kana layout: the place decides.
        CHECK(clipboard_key(8, @"そ", command) == 'c');
        CHECK(clipboard_key(9, @"ひ", command) == 'v');
        // With another modifier, or without Command, the key is an ordinary key.
        CHECK(clipboard_key(9, @"v", command | NSEventModifierFlagShift) == 0);
        CHECK(clipboard_key(9, @"v", command | NSEventModifierFlagOption) == 0);
        CHECK(clipboard_key(8, @"c", command | NSEventModifierFlagControl) == 0);
        CHECK(clipboard_key(8, @"c", NSEventModifierFlagControl) == 0);
        CHECK(clipboard_key(8, @"c", 0) == 0);
        CHECK(clipboard_key(0, @"a", command) == 0);

        // The window's socket address: the path and its NUL, nothing after (the relay reads all
        // but the last byte as the path).
        struct sockaddr_un own;
        const char *at = "/var/folders/ab/cd/T/istesso-viewer-abcdef/w.sock";
        socklen_t length = clipboard_address(&own, at);
        CHECK(length == offsetof(struct sockaddr_un, sun_path) + strlen(at) + 1);
        CHECK(own.sun_len == length && own.sun_family == AF_UNIX);
        CHECK(strcmp(own.sun_path, at) == 0 && own.sun_path[strlen(at)] == 0);
        char too_long[200];
        memset(too_long, 'a', sizeof too_long - 1);
        too_long[sizeof too_long - 1] = 0;
        CHECK(clipboard_address(&own, too_long) == 0);

        // In a password field of the host (state 2) a copy or a cut is refused here; a paste is
        // not, and nothing is refused in another field or without one.
        CHECK(clipboard_refused_here('c', 2));
        CHECK(clipboard_refused_here('x', 2));
        CHECK(!clipboard_refused_here('v', 2));
        CHECK(!clipboard_refused_here('c', 1));
        CHECK(!clipboard_refused_here('x', 0));
        CHECK(!clipboard_refused_here(0, 2));

        // What a paste takes from the pasteboard.
        NSArray *plain = @[@"public.utf8-plain-text"];
        CHECK(clipboard_paste_kind(plain, @"two\nlines\tand tabs\r\n") == PASTE_WITH_TEXT);
        CHECK(clipboard_paste_kind(plain, @"日本語と絵文字🙂") == PASTE_WITH_TEXT);
        CHECK(clipboard_paste_kind(@[@"public.png"], nil) == PASTE_KEY_ONLY);
        CHECK(clipboard_paste_kind(@[], nil) == PASTE_KEY_ONLY);
        for (NSString *secret in @[@"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType",
                                   @"org.nspasteboard.AutoGeneratedType"]) {
            CHECK(clipboard_paste_kind(@[@"public.utf8-plain-text", secret], @"hunter2") == PASTE_SECRET);
            CHECK(clipboard_paste_kind(@[secret], nil) == PASTE_SECRET);
        }
        CHECK(clipboard_paste_kind(plain, @"") == PASTE_NOT_TEXT);
        CHECK(clipboard_paste_kind(plain, @"a\x1b[2Jb") == PASTE_NOT_TEXT);
        CHECK(clipboard_paste_kind(plain, [NSString stringWithFormat:@"a%C", (unichar)0x85]) == PASTE_NOT_TEXT);
        NSString *most = [@"" stringByPaddingToLength:CLIPBOARD_MOST_BYTES withString:@"a" startingAtIndex:0];
        CHECK(clipboard_paste_kind(plain, most) == PASTE_WITH_TEXT);
        CHECK(clipboard_paste_kind(plain, [most stringByAppendingString:@"a"]) == PASTE_TOO_LARGE);
        // Counted in bytes: 21846 characters of three bytes are more than 64 KiB.
        NSString *wide = [@"" stringByPaddingToLength:21846 withString:@"あ" startingAtIndex:0];
        CHECK(clipboard_paste_kind(plain, wide) == PASTE_TOO_LARGE);

        // What the title says.
        CHECK(clipboard_note("text", NULL, NO) == nil);
        CHECK(clipboard_note("pasted", NULL, NO) == nil);
        CHECK([clipboard_note("refused", "secure_input", NO) containsString:@"安全なキー入力"]);
        CHECK([clipboard_note("refused", "password_field", NO) containsString:@"パスワード"]);
        CHECK([clipboard_note("refused", "secret_marker", NO) containsString:@"秘密の印"]);
        CHECK([clipboard_note("refused", "later", NO) containsString:@"パスワード"]);
        CHECK([clipboard_note("none", NULL, YES) containsString:@"⌘Z"]);
        CHECK([clipboard_note("too_large", NULL, YES) containsString:@"⌘Z"]);
        CHECK([clipboard_note("too_large", NULL, NO) containsString:@"64 KB"]);
        CHECK([clipboard_note("paste:secret", NULL, NO) containsString:@"秘密の印"]);
        CHECK(![clipboard_note("paste:secret", NULL, NO) isEqual:clipboard_note("refused", "password_field", NO)]);
        CHECK(clipboard_note("later", NULL, NO) != nil);

        // Reading a paste: only from a pasteboard of this test's own, never the general one
        // (the person uses it all the time).
        NSPasteboard *board = [NSPasteboard pasteboardWithUniqueName];
        CHECK(![board.name isEqual:NSPasteboardNameGeneral]);
        NSString *text = @"left over";
        [board clearContents];
        CHECK(clipboard_read_paste(board, &text) == PASTE_KEY_ONLY && text == nil);
        [board clearContents];
        [board setString:@"二行の\n文字" forType:NSPasteboardTypeString];
        CHECK(clipboard_read_paste(board, &text) == PASTE_WITH_TEXT && [text isEqual:@"二行の\n文字"]);
        [board clearContents];
        NSPasteboardItem *secret = [NSPasteboardItem new];
        [secret setString:@"hunter2" forType:NSPasteboardTypeString];
        [secret setString:@"" forType:@"org.nspasteboard.ConcealedType"];
        [board writeObjects:@[secret]];
        CHECK(clipboard_read_paste(board, &text) == PASTE_SECRET && text == nil);
        [board clearContents];
        [board setString:[@"" stringByPaddingToLength:CLIPBOARD_MOST_BYTES + 1 withString:@"a" startingAtIndex:0] forType:NSPasteboardTypeString];
        CHECK(clipboard_read_paste(board, &text) == PASTE_TOO_LARGE && text == nil);
        [board clearContents];
        [board setString:@"bell\a" forType:NSPasteboardTypeString];
        CHECK(clipboard_read_paste(board, &text) == PASTE_NOT_TEXT && text == nil);
        [board releaseGlobally];
    }
    if (failures == 0) {
        printf("clipboard-test: all passed\n");
    }
    return failures == 0 ? 0 : 1;
}
